"""Generate sim/scene_cup.xml from the measured constants in config.py.

The cup is tapered (wider at the top than the bottom), which MuJoCo has no
single primitive for, so it is approximated as a short stack of cylinders
whose radius shrinks from CUP_TOP_RADIUS to CUP_BOTTOM_RADIUS. The sticky
note is a thin flat box at its real 7.5x7.5cm size, not the round coaster
placeholder the scene used to have.

Run this whenever config.py changes, then re-run build_scene.py to copy the
result next to the hand model:

    python scripts/gen_scene.py
    python scripts/build_scene.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from config import (  # noqa: E402
    CUP_BOTTOM_RADIUS, CUP_HEIGHT, CUP_MASS, CUP_TAPER_SEGMENTS,
    CUP_TOP_RADIUS, STICKY_NOTE_SIDE, STICKY_NOTE_THICKNESS,
    TABLE_HEIGHT, TABLE_TOP_HALF_THICKNESS,
)

OUT = ROOT / "sim" / "scene_cup.xml"


def cup_geoms() -> str:
    """Stack CUP_TAPER_SEGMENTS short cylinders, radius shrinking bottom to
    top, so the body silhouette tapers like the real cup."""
    seg_h = CUP_HEIGHT / CUP_TAPER_SEGMENTS
    lines = []
    for i in range(CUP_TAPER_SEGMENTS):
        # segment i=0 is the bottom, i=last is the top
        frac_lo = i / CUP_TAPER_SEGMENTS
        frac_hi = (i + 1) / CUP_TAPER_SEGMENTS
        r_lo = CUP_BOTTOM_RADIUS + frac_lo * (CUP_TOP_RADIUS - CUP_BOTTOM_RADIUS)
        r_hi = CUP_BOTTOM_RADIUS + frac_hi * (CUP_TOP_RADIUS - CUP_BOTTOM_RADIUS)
        r_mid = (r_lo + r_hi) / 2
        z_mid = -CUP_HEIGHT / 2 + (i + 0.5) * seg_h
        lines.append(
            f'      <geom name="cup_geom_{i}" type="cylinder" '
            f'size="{r_mid:.4f} {seg_h / 2:.4f}" pos="0 0 {z_mid:.4f}" '
            f'material="cup_mat" friction="1.2 0.02 0.001" '
            f'solref="0.004 1" solimp="0.95 0.99 0.001"/>'
        )
    return "\n".join(lines)


def main() -> None:
    # rough inertia for a thin-walled cylinder-ish shell, good enough for sim
    r = (CUP_TOP_RADIUS + CUP_BOTTOM_RADIUS) / 2
    ixx = CUP_MASS * (3 * r * r + CUP_HEIGHT * CUP_HEIGHT) / 12
    izz = CUP_MASS * r * r / 2

    note_half = STICKY_NOTE_SIDE / 2
    note_half_thick = STICKY_NOTE_THICKNESS / 2
    note_z = TABLE_HEIGHT + 2 * TABLE_TOP_HALF_THICKNESS + note_half_thick

    xml = f"""<mujoco model="shadow_cup_scene">
  <!--
    GENERATED by scripts/gen_scene.py from config.py. Do not hand-edit the
    cup/sticky_note geometry here, change config.py and regenerate instead.

    Shadow right hand + table + cup + sticky note (the pick-and-place target).

    This file must sit INSIDE mujoco_menagerie/shadow_hand/ so that the mesh
    paths inside right_hand.xml resolve. scripts/build_scene.py copies it there.
  -->

  <!-- right_hand_free.xml is right_hand.xml with a freejoint on the root body,
       generated by scripts/make_free_hand.py. The stock model is welded to the
       world, which cannot carry a cup anywhere. -->
  <include file="right_hand_free.xml"/>

  <statistic center="0 0 0.2" extent="0.6"/>

  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <global azimuth="130" elevation="-25"/>
  </visual>

  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0" width="512" height="3072"/>
    <texture type="2d" name="groundplane" builtin="checker" mark="edge"
             rgb1="0.2 0.3 0.4" rgb2="0.1 0.2 0.3" markrgb="0.8 0.8 0.8"
             width="300" height="300"/>
    <material name="groundplane" texture="groundplane" texrepeat="5 5" reflectance="0.1"/>
    <material name="table_mat" rgba="0.75 0.68 0.58 1"/>
    <material name="cup_mat" rgba="0.85 0.25 0.2 1"/>
    <material name="sticky_note_mat" rgba="1.0 0.95 0.3 1"/>
  </asset>

  <worldbody>
    <light pos="0 0 1.5" dir="0 0 -1" directional="true"/>
    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane"/>

    <!-- table top at z = {TABLE_HEIGHT} -->
    <body name="table" pos="0 0 {TABLE_HEIGHT / 2:.4f}">
      <geom name="table_top" type="box" size="0.40 0.30 {TABLE_TOP_HALF_THICKNESS}" pos="0 0 {TABLE_HEIGHT / 2 - TABLE_TOP_HALF_THICKNESS:.4f}"
            material="table_mat" friction="1.0 0.01 0.001"/>
      <geom name="table_leg" type="box" size="0.05 0.05 {TABLE_HEIGHT / 2:.4f}" pos="0 0 0"
            material="table_mat" contype="0" conaffinity="0"/>
    </body>

    <!-- sticky note: static target, 7.5x7.5cm, place where you measured it -->
    <body name="sticky_note" pos="0.12 -0.14 {note_z:.4f}">
      <geom name="sticky_note_geom" type="box" size="{note_half:.4f} {note_half:.4f} {note_half_thick:.5f}"
            material="sticky_note_mat" contype="0" conaffinity="0"/>
    </body>

    <!-- cup: free body, tapered via {CUP_TAPER_SEGMENTS} stacked cylinders,
         starting pose overwritten per episode by replay -->
    <body name="cup" pos="0.0 0.10 {TABLE_HEIGHT + CUP_HEIGHT / 2 + 0.005:.4f}">
      <freejoint name="cup_free"/>
      <inertial pos="0 0 0" mass="{CUP_MASS}" diaginertia="{ixx:.6f} {ixx:.6f} {izz:.6f}"/>
{cup_geoms()}
    </body>
  </worldbody>
</mujoco>
"""
    OUT.write_text(xml)
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"cup: top r={CUP_TOP_RADIUS*100:.2f}cm bottom r={CUP_BOTTOM_RADIUS*100:.2f}cm "
          f"height={CUP_HEIGHT*100:.1f}cm, {CUP_TAPER_SEGMENTS} segments")
    print(f"sticky note: {STICKY_NOTE_SIDE*100:.1f}x{STICKY_NOTE_SIDE*100:.1f}cm, "
          f"{STICKY_NOTE_THICKNESS*100:.2f}cm thick")


if __name__ == "__main__":
    main()
